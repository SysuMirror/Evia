"""Generate Go wire types and an offline schema bundle from canonical contracts."""
import copy
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'backend/internal/gen/wire'
SPEC = json.loads((ROOT / 'contracts/http/openapi.json').read_text())
SCHEMAS = copy.deepcopy(SPEC['components']['schemas'])
NAMES = {}
for path in sorted((ROOT / 'contracts').rglob('*.schema.json')):
    name = ''.join(word.title() for word in path.name.removesuffix('.schema.json').split('-'))
    NAMES[path.name] = name
    SCHEMAS[name] = json.loads(path.read_text())

def normalize(value, root):
    if isinstance(value, dict):
        value.pop('$id', None)
        if '$ref' in value:
            ref = value['$ref']
            if ref.startswith('#/components/schemas/'):
                value['$ref'] = '#/$defs/' + ref.rsplit('/', 1)[1]
            elif ref.startswith('#/'):
                value['$ref'] = '#/$defs/' + root + ref[1:]
            elif not ref.startswith('#'):
                file, _, fragment = ref.partition('#')
                value['$ref'] = '#/$defs/' + NAMES[file.rsplit('/', 1)[-1]] + fragment
        for child in value.values():
            normalize(child, root)
    elif isinstance(value, list):
        for child in value:
            normalize(child, root)

for schema_name, schema_value in SCHEMAS.items():
    normalize(schema_value, schema_name)
INITIALISMS = {'id': 'ID', 'ids': 'IDs', 'uid': 'UID', 'url': 'URL', 'csrf': 'CSRF', 'sdk': 'SDK', 'api': 'API'}

def go_name(name):
    return ''.join(INITIALISMS.get(part, part[:1].upper() + part[1:]) for part in name.split('_'))

def go_type(schema):
    if '$ref' in schema:
        parts = schema['$ref'].split('/')
        return parts[2] if len(parts) == 3 else 'json.RawMessage'
    if 'oneOf' in schema or 'anyOf' in schema:
        return 'json.RawMessage'
    kind = schema.get('type')
    if isinstance(kind, list):
        kinds = [x for x in kind if x != 'null']
        if len(kinds) == 1:
            child = dict(schema, type=kinds[0])
            return '*' + go_type(child)
        return 'json.RawMessage'
    if not kind and 'const' in schema and isinstance(schema['const'], int) and not isinstance(schema['const'], bool):
        return 'int64'
    if not kind:
        vals = schema.get('enum', [schema.get('const')])
        if vals and all(isinstance(x, str) for x in vals):
            return 'string'
        return 'json.RawMessage'
    if kind == 'object':
        if 'properties' not in schema:
            return 'map[string]any'
        required = set(schema.get('required', []))
        fields = []
        for name, child in schema['properties'].items():
            typ = go_type(child)
            optional = name not in required
            if optional and not typ.startswith(('*', '[]', 'map[')) and typ != 'json.RawMessage':
                typ = '*' + typ
            tag = name + (',omitempty' if optional else '')
            fields.append(f'{go_name(name)} {typ} `json:"{tag}"`')
        return 'struct {\n' + '\n'.join(fields) + '\n}'
    if kind == 'array':
        return '[]' + go_type(schema.get('items', {}))
    if kind in {'string', 'boolean', 'integer', 'number'}:
        return {'string': 'string', 'boolean': 'bool', 'integer': 'int64', 'number': 'float64'}[kind]
    raise ValueError(f'Unsupported schema type: {kind}')

OUT.mkdir(parents=True, exist_ok=True)
code = '// Code generated by tooling/codegen/generate.py; DO NOT EDIT.\npackage wire\n\nimport "encoding/json"\n\n'
for name, schema in sorted(SCHEMAS.items()):
    code += f'type {name} {go_type(schema)}\n\n'
(OUT / 'types.gen.go').write_text(code)
bundle = {'$schema': 'https://json-schema.org/draft/2020-12/schema', '$id': 'https://schemas.evia.invalid/contracts/v1', '$defs': SCHEMAS}
(OUT / 'contracts.gen.json').write_text(json.dumps(bundle, ensure_ascii=False, separators=(',', ':'), sort_keys=True) + '\n')
print(f'Generated {len(SCHEMAS)} wire types and an offline validation bundle.')
